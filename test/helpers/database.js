import EmbeddedPostgres from 'embedded-postgres';
import pg from 'pg';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createServer } from 'node:net';
import { randomBytes } from 'node:crypto';

const identifier = (value) => {
  if (!/^[a-z_][a-z0-9_]*$/.test(value)) throw new Error('Unexpected fixture identifier');
  return `"${value}"`;
};
async function freePort() {
  const server = createServer();
  await new Promise((resolve, reject) => { server.once('error', reject); server.listen(0, '127.0.0.1', resolve); });
  const { port } = server.address();
  await new Promise((resolve) => server.close(resolve));
  return port;
}

// Reconstruct the inspected production schema in a disposable local cluster.
// This helper never reads DATABASE_URL or .env, and cannot target the live DB.
export async function testDatabase() {
  const directory = await mkdtemp(join(tmpdir(), 'alumni69-test-'));
  const port = await freePort(), password = randomBytes(24).toString('hex');
  let logs = '';
  const postgres = new EmbeddedPostgres({
    databaseDir: join(directory, 'data'), port, user: 'postgres', password,
    authMethod: 'scram-sha-256', persistent: true, autoRehydrateSymlinks: true,
    postgresFlags: ['-h', '127.0.0.1', '-k', directory],
    onLog: (message) => { logs = (logs + message).slice(-12000); },
    onError: (message) => { logs = (logs + String(message)).slice(-12000); },
  });
  let pool;
  try {
    await postgres.initialise();
    await postgres.start();
    pool = new pg.Pool({ host: '127.0.0.1', port, user: 'postgres', password, database: 'postgres', max: 12 });
    const snapshot = JSON.parse(await readFile(new URL('../../docs/database-inspection.json', import.meta.url), 'utf8'));
    await pool.query(`CREATE SCHEMA auth; CREATE TABLE auth.users(id uuid PRIMARY KEY,email text); CREATE SCHEMA alumni_69;
      CREATE ROLE anon NOLOGIN; CREATE ROLE authenticated NOLOGIN; CREATE ROLE service_role NOLOGIN BYPASSRLS;`);
    for (const table of snapshot.tables.filter((table) => table.kind === 'r')) {
      const columns = table.columns.map((column) => `${identifier(column.name)} ${column.type}${column.default ? ` DEFAULT ${column.default}` : column.name === 'id' && column.type === 'bigint' ? ' GENERATED BY DEFAULT AS IDENTITY' : ''}${column.not_null ? ' NOT NULL' : ''}`);
      await pool.query(`CREATE TABLE alumni_69.${identifier(table.name)} (${columns.join(',')})`);
    }
    for (const table of snapshot.tables.filter((table) => table.kind === 'r')) {
      for (const constraint of (table.constraints || []).filter((c) => !c.definition.startsWith('FOREIGN KEY'))) await pool.query(`ALTER TABLE alumni_69.${identifier(table.name)} ADD CONSTRAINT ${identifier(constraint.name)} ${constraint.definition}`);
      if (table.rls) await pool.query(`ALTER TABLE alumni_69.${identifier(table.name)} ENABLE ROW LEVEL SECURITY`);
    }
    for (const table of snapshot.tables.filter((table) => table.kind === 'r')) {
      for (const constraint of (table.constraints || []).filter((c) => c.definition.startsWith('FOREIGN KEY'))) await pool.query(`ALTER TABLE alumni_69.${identifier(table.name)} ADD CONSTRAINT ${identifier(constraint.name)} ${constraint.definition}`);
    }
    for (const index of snapshot.indexes) await pool.query(index.indexdef.replace(' INDEX ', ' INDEX IF NOT EXISTS '));
    for (const fn of snapshot.functions) await pool.query(fn.definition);
    for (const view of snapshot.views) await pool.query(`CREATE VIEW alumni_69.${identifier(view.name)} WITH (security_invoker=true) AS ${view.definition}`);
    await pool.query(`GRANT USAGE ON SCHEMA alumni_69 TO service_role;
      GRANT SELECT,INSERT,UPDATE,DELETE ON ALL TABLES IN SCHEMA alumni_69 TO service_role;
      GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA alumni_69 TO service_role;`);
    await pool.query(await readFile(new URL('../../db/setup-api.sql', import.meta.url), 'utf8'));
    await pool.query(await readFile(new URL('../../db/staff-users.sql', import.meta.url), 'utf8'));
    await pool.query('GRANT USAGE ON SCHEMA auth TO service_role; GRANT SELECT(email,id) ON auth.users TO service_role');
    await pool.query(await readFile(new URL('../../db/supabase-api.sql', import.meta.url), 'utf8'));
    await pool.query(`INSERT INTO alumni_69.event_tables(id,zone,column_label,table_number,kind)
      SELECT 'A'||n,1,'A',n,'regular' FROM generate_series(1,40) n;
      INSERT INTO alumni_69.event_tables(id,zone,column_label,table_number,kind) VALUES('STAFF1',1,'S',1,'staff');
      INSERT INTO alumni_69.reserved_areas VALUES('VIP','VIP',1,'blue-white')`);
    return { pool, postgres, directory, async close() {
      await pool.end(); await postgres.stop(); await rm(directory, { recursive: true, force: true });
    } };
  } catch (error) {
    if (pool) await pool.end();
    await postgres.stop().catch(() => {});
    await rm(directory, { recursive: true, force: true });
    throw new Error(`Disposable PostgreSQL could not start: ${error?.message || logs}`);
  }
}
